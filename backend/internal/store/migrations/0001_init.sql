-- Shared content: exercises. Never holds anything personal.
CREATE TABLE exercises (
    id               BIGSERIAL PRIMARY KEY,
    slug             TEXT NOT NULL UNIQUE,            -- stable key, makes seeding idempotent
    type             TEXT NOT NULL CHECK (type IN ('vocab', 'writing')),
    context          TEXT,                            -- vocab: the sentence containing the target word
    prompt           TEXT NOT NULL,                   -- the instruction or question shown to the learner
    target_word      TEXT,
    intended_meaning TEXT,                            -- reference meaning, used only for evaluation
    expected_length  TEXT,
    criteria         JSONB NOT NULL DEFAULT '[]'::jsonb,
    topic            TEXT NOT NULL,
    cefr             TEXT NOT NULL CHECK (cefr IN ('A2', 'B1', 'B2', 'C1')),   -- approximate
    source           TEXT NOT NULL DEFAULT 'original', -- provenance: original, owner_anki, adapted, ...
    status           TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('draft', 'published', 'rejected')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT vocab_needs_word CHECK (
        type <> 'vocab' OR (target_word IS NOT NULL AND intended_meaning IS NOT NULL AND context IS NOT NULL)
    )
);
CREATE INDEX exercises_selection_idx ON exercises (status, type);

-- Immutable history of what the learner submitted and how it was evaluated.
-- The attempt id is generated by the browser and doubles as an idempotency key.
CREATE TABLE attempts (
    id                UUID PRIMARY KEY,
    exercise_id       BIGINT NOT NULL REFERENCES exercises (id),
    parent_attempt_id UUID REFERENCES attempts (id),   -- set when this is a rewrite of an earlier attempt
    answer            TEXT NOT NULL CHECK (char_length(answer) BETWEEN 1 AND 1000),
    status            TEXT NOT NULL CHECK (status IN ('pending', 'evaluated', 'failed')),
    verdict           TEXT CHECK (verdict IN ('correct', 'mostly_correct', 'partially_correct', 'incorrect')),
    confidence        TEXT CHECK (confidence IN ('high', 'medium', 'low')),
    evaluation        JSONB,                           -- the validated feedback shown to the learner
    raw_response      TEXT,                            -- raw model text, kept to audit bad corrections
    model             TEXT,
    prompt_version    TEXT,
    provider_calls    INT,
    dropped_issues    INT,
    failure_code      TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    evaluated_at      TIMESTAMPTZ,
    CONSTRAINT evaluated_has_result CHECK (
        status <> 'evaluated' OR (verdict IS NOT NULL AND evaluation IS NOT NULL AND evaluated_at IS NOT NULL)
    )
);
CREATE INDEX attempts_created_idx ON attempts (created_at DESC);
CREATE INDEX attempts_exercise_idx ON attempts (exercise_id, created_at DESC);
CREATE INDEX attempts_parent_idx ON attempts (parent_attempt_id);

-- One row per issue in an accepted evaluation. Derived from attempts.evaluation,
-- kept as real columns so statistics are plain SQL instead of JSON digging.
CREATE TABLE attempt_issues (
    id         BIGSERIAL PRIMARY KEY,
    attempt_id UUID NOT NULL REFERENCES attempts (id) ON DELETE CASCADE,
    position   INT NOT NULL,
    category   TEXT NOT NULL,
    severity   TEXT NOT NULL CHECK (severity IN ('error', 'unnatural', 'style'))
);
CREATE INDEX attempt_issues_attempt_idx ON attempt_issues (attempt_id);
CREATE INDEX attempt_issues_category_idx ON attempt_issues (category, severity);
